export function getCountryConfig(countryCode: string = 'RW'): GeoCountryConfig {
  const code = (countryCode || 'RW').toUpperCase();
  return (
    SUPPORTED_COUNTRIES[code] || {
      ...SUPPORTED_COUNTRIES.RW,
      countryCode: code,
      name: code,
      nativeName: code,
      flagEmoji: '🌍',
    }
  );
}

export function getAllCountries(): GeoCountryConfig[] {
  return Object.values(SUPPORTED_COUNTRIES).filter((c) => c.enabled);
}
